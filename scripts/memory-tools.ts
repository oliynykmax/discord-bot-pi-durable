// Saves the memory server's tools/list as src/memory-tools.ts. Run after upgrading Basic Memory on the VM:
//   SHELL_TOKEN=... node scripts/memory-tools.ts
import { writeFileSync } from "node:fs";
import { MemoryServer } from "../src/memory.ts";

const token = process.env.SHELL_TOKEN;
if (!token) throw new Error("SHELL_TOKEN is not set");
const server = new MemoryServer(process.env.MEMORY_MCP_URL ?? "https://138-2-191-62.sslip.io/mcp", token);
const tools = await server.tools();
server.close();
const header = "// Generated by scripts/memory-tools.ts from the memory server's tools/list. Do not edit by hand.\n";
writeFileSync(new URL("../src/memory-tools.ts", import.meta.url), `${header}export const SNAPSHOT = ${JSON.stringify(tools, null, "\t")};\n`);
console.log(`saved ${tools.length} tools: ${tools.map((tool) => tool.name).join(", ")}`);
